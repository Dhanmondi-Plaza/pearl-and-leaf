const selector = document.getElementById('language');
const supported = ['en', 'bn', 'es', 'zh-CN'];
const params = new URLSearchParams(location.search);
let saved;
try { saved = localStorage.getItem('pearl-leaf-language'); } catch {}
const initial = supported.includes(params.get('lang')) ? params.get('lang') : supported.includes(saved) ? saved : 'en';

function setLanguage(language) {
  if (!supported.includes(language)) return;
  document.documentElement.lang = language;
  selector.value = language;
  if (language !== 'en') {
    const copy = translations[language];
    document.querySelectorAll('[data-i18n]').forEach(element => {
      element.textContent = copy[element.dataset.i18n];
    });
    document.querySelectorAll('[data-i18n-html]').forEach(element => {
      element.innerHTML = copy[element.dataset.i18nHtml];
    });
  } else if (setLanguage.english) {
    document.querySelectorAll('[data-i18n]').forEach(element => {
      element.textContent = setLanguage.english[element.dataset.i18n];
    });
    document.querySelectorAll('[data-i18n-html]').forEach(element => {
      element.innerHTML = setLanguage.english[element.dataset.i18nHtml];
    });
  }
  try { localStorage.setItem('pearl-leaf-language', language); } catch {}
}

setLanguage.english = Object.fromEntries(
  [...document.querySelectorAll('[data-i18n], [data-i18n-html]')].map(element => [
    element.dataset.i18n || element.dataset.i18nHtml,
    element.dataset.i18nHtml ? element.innerHTML : element.textContent
  ])
);
setLanguage(initial);
selector.addEventListener('change', () => {
  setLanguage(selector.value);
  const url = new URL(location.href);
  if (selector.value === 'en') url.searchParams.delete('lang');
  else url.searchParams.set('lang', selector.value);
  history.replaceState(null, '', url);
});
